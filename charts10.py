# Chart section of each question of the 10th-grade exam (chapter 1 — the living world).
# usage: python3 charts10.py <out dir> [background colour]
import json, math, os, sys
import svgfig
from svgfig import Fig, Axes, fa, PAL, BLUE, GREEN, RED, GOLD, GRAY, PURPLE

W = 900
CH = {}


def chart(n):
    def deco(fn):
        CH[n] = fn
        return fn
    return deco


def footer(f, s, color="#555", size=14, weight=400):
    f.text(W / 2, f.h - 16, s, size, weight=weight, color=color)


LEVELS = ["یاخته", "بافت", "اندام", "دستگاه", "جاندار", "جمعیت", "اجتماع", "بوم‌سازگان", "زیست‌بوم", "زیست‌کره"]


def ladder(f, y0, hl=(), notes=None, h=34, gap=6, x0=300, x1=640):
    """vertical ladder of the 10 levels of organisation, bottom = cell"""
    for i, name in enumerate(LEVELS):
        y = y0 + (len(LEVELS) - 1 - i) * (h + gap)
        k = "p" if i in hl else ("g" if i <= 4 else "b")
        w = 160 + i * 18
        f.box((x0 + x1) / 2 - w / 2, y, w, h, "%s. %s" % (fa(i + 1), name), k, 14.5)
        if notes and notes.get(i):
            f.line((x0 + x1) / 2 + w / 2 + 6, y + h / 2, (x0 + x1) / 2 + w / 2 + 26, y + h / 2, "#BBB", 1.5)
            f.text((x0 + x1) / 2 + w / 2 + 32, y + h / 2, notes[i], 13, anchor="end", color="#444")
    return y0 + len(LEVELS) * (h + gap)


